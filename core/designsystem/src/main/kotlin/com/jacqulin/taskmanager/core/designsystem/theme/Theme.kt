@Composable
fun TaskManagerTheme(
    darkTheme: Boolean = isSystemInDarkTheme(),
    colorPalette: ColorPalette = ColorPalette.GREEN,
    content: @Composable () -> Unit
) {
    val colorScheme = when (colorPalette) {
        ColorPalette.GREEN -> if (darkTheme) darkGreenScheme else lightGreenScheme
        ColorPalette.CYAN -> if (darkTheme) darkCyanScheme else lightCyanScheme
        ColorPalette.ORANGE -> if (darkTheme) darkOrangeScheme else lightOrangeScheme
        ColorPalette.PURPLE -> if (darkTheme) darkPurpleScheme else lightPurpleScheme
        ColorPalette.PINK -> if (darkTheme) darkPinkScheme else lightPinkScheme
        ColorPalette.MALACHITE -> if (darkTheme) darkMalachiteScheme else lightMalachiteScheme
        ColorPalette.AMBER -> if (darkTheme) darkAmberScheme else lightAmberScheme
        ColorPalette.BLUE -> if (darkTheme) darkBlueScheme else lightBlueScheme
    }

    MaterialTheme(
        colorScheme = colorScheme,
        typography = Typography,
        content = content
    )
}
